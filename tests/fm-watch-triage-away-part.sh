    FM_STATE_OVERRIDE="$state" FM_CREW_STATE_BIN="$fakebin/fm-crew-state.sh" FM_STALE_ESCALATE_SECS=240 \
    FM_WEDGE_DEMAND_INSPECT_COUNT=3 FM_POLL=1 FM_SIGNAL_GRACE=1 \
    FM_CHECK_INTERVAL=999999 FM_HEARTBEAT=999999 "$WATCH" > "$out" &
  pid=$!
  wait_for_exit_scaled "$pid" 100 || fail "the third picker wedge did not escalate: $(cat "$out")"
  grep -F 'possible wedge, escalation 3' "$out" >/dev/null || fail "the ladder did not reach escalation 3: $(cat "$out")"
  grep -F 'demand-deep-inspection: same pane has wedge-escalated 3 times in a row - do not re-absorb on the run-step/pane state alone, blocked-on-prompt: Claude background-task exit picker' \
    "$out" >/dev/null || fail "the dialog name was not after demand-deep-inspection: $(cat "$out")"
  n=$(cat "$state/.wedge-escalations-$key" 2>/dev/null || echo 0)
  [ "$n" -eq 3 ] || fail "the escalation count was $n, not 3"
  [ "$(cat "$state/.wedge-backoff-$key")" = 2 ] || fail "the picker did not grow backoff on the next escalation"
  ack_stopped_cycle "$state" || fail "could not acknowledge picker escalation 3"

  # Close the picker and seed the observed hash as already stale to drive the
  # next wedge check, rather than resetting the ladder through pane activity.
  printf 'idle at the prompt\n' > "$capture_file"
  printf '%s' "$(hash_text "$(cat "$capture_file")")" > "$state/.hash-$key"
  printf '%s' "$(hash_text "$(cat "$capture_file")")" > "$state/.stale-$key"
  printf '%s' 'Claude background-task exit picker' > "$state/.subsuper-dialog-picker"
  echo $(( $(date +%s) - 500 )) > "$state/.stale-since-$key"
  : > "$out"
  FM_TEST_STALE_ESCALATE=240 wedge_threshold_round "$state" "$fakebin" "$out" "$capture_file" "$window" \
    "$FM_FAKE_CREW_STATE" absorb || fail "a closed picker ignored the doubled 960s threshold: $(cat "$out")"
  [ "$(cat "$state/.wedge-escalations-$key")" = 3 ] || fail "the ladder advanced before the doubled threshold"
  [ ! -e "$state/.subsuper-dialog-picker" ] || fail "the closed picker kept its saved dialog name"
  ack_stopped_cycle "$state" || fail "could not acknowledge the closed-picker absorb"
  echo $(( $(date +%s) - 1000 )) > "$state/.stale-since-$key"
  : > "$out"
  FM_TEST_STALE_ESCALATE=240 wedge_threshold_round "$state" "$fakebin" "$out" "$capture_file" "$window" \
    "$FM_FAKE_CREW_STATE" exit || fail "a closed picker did not escalate after the doubled threshold: $(cat "$out")"
  grep -F 'possible wedge, escalation 4' "$out" >/dev/null || fail "the closed picker lost its wedge ladder: $(cat "$out")"
  grep -F 'blocked-on-prompt' "$out" >/dev/null && fail "the closed picker still named a blocking dialog: $(cat "$out")"
  [ "$(cat "$state/.wedge-backoff-$key")" = 3 ] || fail "the closed picker did not retain backoff growth"
  unset FM_FAKE_CREW_STATE
  pass "exit-picker wedges retain growing backoff and clear the dialog name when the picker closes"
}

